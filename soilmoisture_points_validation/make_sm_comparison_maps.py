"""Create trained-vs-untrained soil-moisture comparison maps.

The "untrained" map is the shipped model6 prediction already generated by
``run_validation.py``. The "trained" map is a local residual-calibrated variant:
fit a ridge residual corrector from the dense point/date observations and the
actual model6 inputs, then apply that correction to every pixel.

This is not full OzNet+local model retraining. It is a local calibration surface
on top of model6, intended for visualising how dense local observations change
the predicted soil-moisture field.
"""
