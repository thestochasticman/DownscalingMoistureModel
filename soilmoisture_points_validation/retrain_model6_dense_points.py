"""Retrain model6-style HGBR on the dense point dataset with larger leaves.

This is a local-device retrain: it uses the dense point/date feature table
generated by ``dense_validation_and_spiking.py`` and fits the model6 feature set
directly to the dense observations.

It is intentionally separate from the shipped OzNet model6 artifact. The output
is a local model and map set for this dense site/device.
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

